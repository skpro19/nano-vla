#!/usr/bin/env python3
"""Execute recorded demonstration actions in a live LIBERO environment.

Unlike replay_in_mujoco.py, only the initial recorded state is restored; all
subsequent states are generated by the controller and MuJoCo physics. GUI mode
uses the native MuJoCo viewer. Press Q or close the window to stop.

Examples:
    uv run python scripts/replay_in_libero_env.py --task between --episode 0
    uv run python scripts/replay_in_libero_env.py --task between --headless --max-frames 100
    uv run python scripts/replay_in_libero_env.py --task between --compare-states
"""
from __future__ import annotations

from contextlib import nullcontext
import json
import math
from pathlib import Path
import sys
from threading import Event
import time

from replay_in_mujoco import (
    build_parser as state_parser, discover_tasks, episode_names,
    isolated_libero_config, libero_root, playback_order, repair_model_xml, text,
)


def build_parser():
    parser = state_parser()
    parser.description = __doc__
    parser.set_defaults(fps=None)
    # The recorded control frequency controls physics; fps only paces the viewer.
    for action in parser._actions:
        if action.dest == "fps":
            action.help = "viewer frame rate (default: recorded control frequency); does not change physics"
        elif action.dest == "headless":
            action.help = "execute actions without creating a viewer or renderer"
        elif action.dest == "max_frames":
            action.help = "total action budget across selected episodes; headless default: 100"
    parser.add_argument("--compare-states", action="store_true",
                        help="report L2 error against recorded next states (drift is expected)")
    return parser


def environment_spec(data, root):
    """Resolve portable task metadata, preserving the recorded controller config."""
    metadata = json.loads(text(data.attrs["env_args"]))
    kwargs = dict(metadata["env_kwargs"])
    recorded = data.attrs.get("bddl_file_name", metadata.get("bddl_file", ""))
    parts = text(recorded).replace("\\", "/").split("/")
    if "bddl_files" not in parts:
        raise ValueError("Task metadata must identify a path under bddl_files")
    relative = Path(*parts[parts.index("bddl_files") + 1:])
    base = (root / "bddl_files").resolve()
    bddl = (base / relative).resolve()
    if not bddl.is_relative_to(base) or not bddl.is_file():
        raise ValueError(f"Task BDDL not found: {bddl}")
    # Do not render during env.step; the native viewer displays the live sim.
    kwargs.update(bddl_file_name=str(bddl), has_renderer=False,
                  has_offscreen_renderer=False, use_camera_obs=False,
                  ignore_done=True, hard_reset=False)
    frequency = float(kwargs.get("control_freq", 20))
    if not math.isfinite(frequency) or frequency <= 0:
        raise ValueError("Recorded control_freq must be finite and positive")
    return metadata["problem_name"], kwargs, frequency


def initialize_episode(env, episode, root, robosuite_root):
    """Restore XML and initial state once, never overwrite action-generated states."""
    states = episode["states"]
    if states.ndim != 2 or not len(states):
        raise ValueError("Episode states must be a nonempty 2D array")
    xml = repair_model_xml(episode.attrs["model_file"], robosuite_root, root)
    env.reset()
    env.reset_from_xml_string(xml)
    env.sim.reset()
    expected = env.sim.get_state().flatten().size
    if states.shape[1] != expected:
        raise ValueError(f"States have width {states.shape[1]}; environment expects {expected}")
    env.sim.set_state_from_flattened(states[0])
    env.sim.forward()
    env._update_observables(force=True)


def configure_viewer(viewer, sim):
    import mujoco
    import numpy as np

    with viewer.lock():
        viewer.opt.geomgroup[0] = 0
        viewer.opt.geomgroup[1] = 1
        camera = mujoco.mj_name2id(sim.model._model, mujoco.mjtObj.mjOBJ_CAMERA, "agentview")
        if camera >= 0:
            forward = -sim.data._data.cam_xmat[camera].reshape(3, 3)[:, 2]
            viewer.cam.lookat[:] = sim.data._data.cam_xpos[camera] + forward
            viewer.cam.distance = 1.6
            viewer.cam.azimuth = np.degrees(np.arctan2(forward[1], forward[0]))
            viewer.cam.elevation = np.degrees(np.arcsin(np.clip(forward[2], -1, 1)))


def replay(args, tasks):
    import h5py
    import numpy as np
    import robosuite

    root = libero_root()
    budget = args.max_frames or (100 if args.headless else math.inf)
    count = 0
    quit_requested = Event()

    def on_key(key):
        if key in (ord("Q"), ord("q")):
            quit_requested.set()

    with isolated_libero_config(root, args.data_dir):
        # Import only after seeding config: upstream otherwise prompts/writes ~/.libero.
        # Upstream's editable distribution omits its namespace packages.
        checkout = str(root.parents[1])
        if checkout not in sys.path:
            sys.path.insert(0, checkout)
        # This is LIBERO's registered task implementation, also used by ControlEnv.
        from libero.libero.envs import TASK_MAPPING

        for task in playback_order(tasks, args.no_random):
            with h5py.File(task, "r") as file:
                data = file["data"]
                problem, kwargs, frequency = environment_spec(data, root)
                if problem not in TASK_MAPPING:
                    raise ValueError(f"Unknown LIBERO problem: {problem}")
                for name in playback_order(episode_names(data, args.episode), args.no_random):
                    episode = data[name]
                    actions = episode["actions"]
                    if actions.ndim != 2:
                        raise ValueError(f"{task.name}/{name}: actions must be a 2D array")
                    if not len(actions):
                        print(f"Skipping empty episode {task.name}/{name}", file=sys.stderr)
                        continue
                    env = TASK_MAPPING[problem](**kwargs)
                    try:
                        if actions.shape[1] != env.action_dim:
                            raise ValueError(f"Actions have width {actions.shape[1]}; expected {env.action_dim}")
                        initialize_episode(env, episode, root, Path(robosuite.__file__).parent)
                        context = nullcontext(None)
                        if not args.headless:
                            import mujoco.viewer
                            context = mujoco.viewer.launch_passive(
                                env.sim.model._model, env.sim.data._data, key_callback=on_key)
                        print(f"Executing {task.name}/{name}: {len(actions)} recorded actions "
                              f"at {frequency:g} Hz", flush=True)
                        errors = []
                        executed = 0
                        success = False
                        with context as viewer:
                            if viewer is not None:
                                configure_viewer(viewer, env.sim)
                            deadline = time.monotonic()
                            for index, action in enumerate(actions):
                                if quit_requested.is_set() or (viewer is not None and not viewer.is_running()):
                                    return count
                                if not np.isfinite(action).all():
                                    raise ValueError(f"{task.name}/{name}: nonfinite action at {index}")
                                with viewer.lock() if viewer is not None else nullcontext():
                                    env.step(action)
                                    success = bool(env._check_success()) or success
                                    if args.compare_states and index + 1 < len(episode["states"]):
                                        errors.append(float(np.linalg.norm(
                                            env.sim.get_state().flatten() - episode["states"][index + 1])))
                                executed += 1
                                count += 1
                                if viewer is not None:
                                    viewer.sync()
                                if count >= budget:
                                    break
                                if viewer is not None:
                                    deadline += 1 / ((args.fps or frequency) * args.speed)
                                    time.sleep(max(0, deadline - time.monotonic()))
                        status = "complete" if executed == len(actions) else "truncated by action budget"
                        print(f"  {executed}/{len(actions)} actions ({status}); success reached: {success}")
                        if errors:
                            print(f"  Next-state L2 drift: mean={np.mean(errors):.6g}, max={max(errors):.6g} "
                                  f"over {len(errors)} comparisons")
                        if count >= budget:
                            return count
                    finally:
                        env.close()
    if not count:
        raise ValueError("No nonempty episodes to replay")
    return count


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        tasks = discover_tasks(args.data_dir, args.task or ("all" if args.list else None))
        if args.list:
            import h5py
            for task in tasks:
                print(task)
                with h5py.File(task, "r") as file:
                    for name in episode_names(file["data"]):
                        actions = file["data"][name].get("actions")
                        print(f"  {name}: {len(actions) if actions is not None else 'missing'} actions")
            return 0
        print(f"Executed {replay(args, tasks)} actions")
        return 0
    except (ValueError, OSError, ImportError, KeyError, RuntimeError) as exc:
        parser.exit(1, f"error: {exc}\n")
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
